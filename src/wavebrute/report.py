"""Report generation for audits (PDF, Markdown, HTML)."""

from __future__ import annotations

import os
from datetime import datetime
from typing import Any

from jinja2 import Template  # used for potential future templating


class ReportBuilder:
    """Builds professional reports from audit results.

    Supports PDF (ReportLab), Markdown and HTML with neo-brutalist styling.
    """

    @staticmethod
    def from_results(results: list[dict[str, Any]]) -> ReportBuilder:
        builder = ReportBuilder()
        builder.results = list(results)
        return builder

    def __init__(self) -> None:
        self.results: list[dict[str, Any]] = []

    def render_template(self, title: str, fmt: str = "pdf") -> str:
        """Render report content for the requested format."""
        if fmt == "md":
            content = f"# {title}\n\n## WaveBrute Ethical Audit Report\n\n"
            content += f"**Generated:** {datetime.now().isoformat()}\n\n"
            content += "## Summary\n\n"
            content += f"Total results: {len(self.results)}\n\n"
            for result in self.results:
                content += f"### {result.get('type', 'Result').replace('_', ' ').title()}\n"
                if "ssid" in result:
                    content += f"- SSID: {result['ssid']}\n"
                if "success" in result:
                    content += f"- Success: {result['success']}\n"
                if "password" in result and result.get("password"):
                    content += f"- Cracked password: {result['password']}\n"
                content += "\n"
            content += "\n**Recommendations:** Use strong unique passwords, enable WPA3, disable WPS.\n"
            content += "\n---\nGenerated by WaveBrute (https://github.com/ajendras/wavebrute)"
            return content

        if fmt == "html":
            content = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>{title}</title>
    <style>
        body {{ background-color: #111111; color: #00ff9f; font-family: 'Courier New', monospace; margin: 40px; }}
        h1 {{ color: #ff004d; border: 8px solid #ff00ff; padding: 20px; text-align: center; }}
        h2 {{ color: #ffff00; border-bottom: 4px solid #00ffff; }}
        .brutalist {{ border: 6px solid #ff004d; padding: 15px; margin: 20px 0; background: #222; }}
    </style>
</head>
<body>
    <h1>{title}</h1>
    <p style="text-align:center; color:#ffff00;">ETHICAL AUDIT REPORT — SIMULATION MODE</p>
    <div class="brutalist">
        <h2>Findings</h2>
        <ul>
"""
            for r in self.results:
                content += f"            <li>{r.get('type', '')} on {r.get('ssid', 'N/A')}: success = {r.get('success', 'N/A')}</li>\n"
            content += """        </ul>
    </div>
    <div class="brutalist">
        <h2>Responsible Disclosure</h2>
        <p>This report was generated by WaveBrute for educational purposes only.
        Always obtain explicit written permission before testing networks.</p>
    </div>
    <footer style="text-align:center; margin-top:50px; color:#666;">
        WaveBrute v0.1.0 • Neo-brutalist design
    </footer>
</body>
</html>"""
            return content

        return "PDF content would be rendered here"

    def to_pdf(
        self, title: str = "WaveBrute Ethical Audit Report", output_path: str | None = None
    ) -> str:
        """Generate PDF report using ReportLab.

        Falls back to Markdown on any ReportLab error (e.g. missing fonts
        or CI environments without full PDF support).
        """
        if output_path is None:
            output_path = f"wavebrute_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"

        try:
            from reportlab.lib import colors
            from reportlab.lib.pagesizes import A4
            from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
            from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

            doc = SimpleDocTemplate(output_path, pagesize=A4, rightMargin=30, leftMargin=30)
            styles = getSampleStyleSheet()
            title_style = ParagraphStyle(
                "TitleStyle", parent=styles["Title"], textColor=colors.red, spaceAfter=30
            )
            story = [Paragraph(title, title_style), Spacer(1, 20)]
            story.append(Paragraph("Simulation Mode - Safe Educational Audit", styles["Normal"]))
            story.append(Spacer(1, 30))

            data = [["Type", "SSID", "Success", "Notes"]]
            for res in self.results[:10]:
                row = [
                    res.get("type", "N/A").replace("_", " "),
                    res.get("ssid", "N/A"),
                    str(res.get("success", "N/A")),
                    "See log for details",
                ]
                data.append(row)

            table = Table(data, colWidths=[120, 120, 60, 200])
            table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, 0), colors.pink),
                        ("TEXTCOLOR", (0, 0), (-1, 0), colors.black),
                        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                        ("BACKGROUND", (0, 1), (-1, -1), colors.lightgrey),
                        ("GRID", (0, 0), (-1, -1), 1, colors.black),
                    ]
                )
            )
            story.append(table)
            story.append(Spacer(1, 30))
            story.append(Paragraph("Recommendations:", styles["Heading2"]))
            story.append(
                Paragraph(
                    "• Use passwords longer than 20 characters with mixed symbols.<br/>"
                    "• Prefer WPA3 encryption.<br/>"
                    "• Disable WPS and guest networks when possible.<br/>"
                    "• Regularly monitor for rogue access points.",
                    styles["Normal"],
                )
            )
            doc.build(story)
            return os.path.abspath(output_path)
        except Exception as exc:
            # Fallback to Markdown when PDF generation is unavailable
            md_path = output_path.replace(".pdf", ".md")
            with open(md_path, "w", encoding="utf-8") as f:
                f.write(self.render_template(title, "md"))
            print(f"PDF generation failed ({exc}), saved Markdown fallback to {md_path}")
            return os.path.abspath(md_path)

    def to_markdown(
        self, title: str = "WaveBrute Ethical Audit Report", output_path: str | None = None
    ) -> str:
        """Save report as Markdown."""
        if output_path is None:
            output_path = f"wavebrute_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.md"
        content = self.render_template(title, "md")
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)
        return os.path.abspath(output_path)

    def to_html(
        self, title: str = "WaveBrute Ethical Audit Report", output_path: str | None = None
    ) -> str:
        """Save report as HTML with neo-brutalist styling."""
        if output_path is None:
            output_path = f"wavebrute_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.html"
        content = self.render_template(title, "html")
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)
        return os.path.abspath(output_path)
